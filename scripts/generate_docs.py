"""
Generate the catalogue documentation from the configuration.

The same validated catalogue that is synchronised into the meta schema
is rendered as Markdown under docs/catalogue/, so documentation can never
drift from what the pipeline actually does. The unit tests fail if the
committed files are out of date.

    python scripts/generate_docs.py           # write docs/catalogue/*.md
    python scripts/generate_docs.py --check   # exit 1 if they are stale
"""

import argparse
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

sys.path.insert(0, str(ROOT / "src" / "validation"))
sys.path.insert(0, str(ROOT / "src" / "warehouse"))

from metadata_sync import Catalogue, plan  # noqa: E402

OUTPUT = ROOT / "docs" / "catalogue"
HEADER = "<!-- GENERATED by scripts/generate_docs.py from config/ - do not edit by hand. -->\n\n"


def cell(value) -> str:
    if value is None or value == "":
        return ""
    return str(value).replace("|", "\\|").replace("\n", " ")


def table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def source_catalogue(catalogue: Catalogue) -> str:
    rows = [
        [
            s["SourceName"],
            s["SourceType"],
            s["PathPattern"],
            s["StagingTable"],
            s["SystemOfRecord"],
            s["DataOwner"],
            s["DataSteward"],
            s["Classification"],
            "Yes" if s["ContainsPersonalData"] else "No",
            s["RetentionYears"],
            s["UpdateFrequency"],
            s["FreshnessThresholdHours"],
            "Yes" if s["IsCritical"] else "",
        ]
        for s in catalogue.sources
    ]
    return (
        HEADER
        + "# Source system catalogue\n\n"
        + "Every source the platform ingests or generates, with its owner, steward, classification, "
        "retention and freshness expectation. Critical sources hold the whole warehouse load when blocked.\n\n"
        + table(
            [
                "Source",
                "Type",
                "Path",
                "Staging table",
                "System of record",
                "Data owner",
                "Data steward",
                "Classification",
                "Personal data",
                "Retention (years)",
                "Update frequency",
                "Freshness (hours)",
                "Critical",
            ],
            rows,
        )
        + "\nDescriptions:\n\n"
        + "".join(f"- **{s['SourceName']}**: {s['Description']}\n" for s in catalogue.sources)
    )


def data_dictionary(catalogue: Catalogue) -> str:
    parts = [
        HEADER,
        "# Data dictionary\n\n",
        "Business definitions, staging types and validation rules of every source column. "
        "Personal data is classified CONFIDENTIAL or RESTRICTED and masked in the warehouse.\n",
    ]
    by_source = defaultdict(list)
    for element in catalogue.elements:
        by_source[element["SourceName"]].append(element)
    for source, elements in by_source.items():
        parts.append(f"\n## {source} ({elements[0]['StagingColumn'].rsplit('.', 1)[0]})\n\n")
        parts.append(f"Domain: {elements[0]['Domain'] or '-'}. {elements[0]['EntityDefinition']}\n\n")
        parts.append(
            table(
                ["Column", "Definition", "Type", "Nullable", "Key", "Classification", "Validation rules"],
                [
                    [
                        e["ElementName"],
                        e["BusinessDefinition"],
                        e["DataType"],
                        "Yes" if e["IsNullable"] else "No",
                        "Yes" if e["IsBusinessKey"] else "",
                        e["DataClassification"] + (" (personal)" if e["ContainsPersonalData"] else ""),
                        e["ValidationRule"],
                    ]
                    for e in elements
                ],
            )
        )
    return "".join(parts)


def mappings(catalogue: Catalogue) -> str:
    dependencies = defaultdict(list)
    for child, parent in catalogue.dependencies:
        dependencies[child].append(parent)
    parts = [
        HEADER,
        "# Source-to-target mappings and lineage\n\n",
        "Each mapping is executed by one approved handler (src/warehouse/handlers.py) in dependency "
        "order. Column lineage shows where every warehouse column comes from and how it is derived; "
        "technical columns (lineage, row hash, audit) are documented in docs/warehouse_design.md.\n\n",
        table(
            ["Mapping", "Source", "Target", "Layer", "Strategy", "Handler", "Order", "Depends on"],
            [
                [
                    m["MappingCode"],
                    m["SourceName"],
                    f"{m['TargetSchema']}.{m['TargetTable']}",
                    m["LoadLayer"],
                    m["LoadStrategy"],
                    m["HandlerCode"],
                    m["ExecutionOrder"],
                    ", ".join(dependencies[m["MappingCode"]]),
                ]
                for m in catalogue.mappings
            ],
        ),
    ]
    lineage = defaultdict(list)
    for entry in catalogue.lineage:
        lineage[entry["TargetObject"]].append(entry)
    for target, entries in lineage.items():
        if not target.startswith("dw."):
            continue
        parts.append(f"\n## {target}\n\nSource: {entries[0]['SourceName']} via {entries[0]['SourceObject']}\n\n")
        parts.append(
            table(
                ["Column", "From", "Transformation"],
                [[e["TargetColumn"], e["SourceColumns"], e["TransformationRule"]] for e in entries],
            )
        )
    parts.append(
        "\n## Staging lineage\n\nEvery staging column is the validated source value converted to the "
        "staging type (no business logic); see the data dictionary for the source columns.\n"
    )
    return "".join(parts)


def quality_rules(catalogue: Catalogue) -> str:
    parts = [
        HEADER,
        "# Data quality and business rules catalogue\n\n",
        "## Validation rules (before staging)\n\n",
        "Applied to every source file by src/validation; a failed ERROR rule blocks the file at the load "
        "gate. DQ dimensions follow DAMA-DMBOK (completeness, uniqueness, validity, consistency, accuracy).\n\n",
        table(
            ["Rule", "Stage", "Field", "Severity", "DQ dimension", "Definition", "Owner"],
            [
                [
                    r["RuleCode"],
                    r["RuleStage"],
                    r["FieldName"],
                    r["Severity"],
                    r["DqDimension"],
                    r["Definition"],
                    r["RuleOwner"],
                ]
                for r in catalogue.rules
            ],
        ),
        "\n## Reconciliation controls (after each load)\n\n",
        "CRITICAL and ERROR controls are mandatory quality gates: a failure fails the mapping and stops "
        "the pipeline. WARNING controls are recorded and reported.\n\n",
        table(
            ["Control", "Mapping", "Handler", "Severity", "Mandatory", "Tolerance", "Parameters / justification"],
            [
                [
                    c["ControlCode"],
                    c["MappingCode"],
                    c["HandlerCode"],
                    c["Severity"],
                    "Yes" if c["IsMandatory"] else "No",
                    c["Tolerance"],
                    c["Description"] or c["ParametersJson"],
                ]
                for c in catalogue.controls
            ],
        ),
        "\n## Business-rule parameters (meta.Setting)\n\n",
        table(
            ["Setting", "Value", "Type"],
            [[s["SettingKey"], s["SettingValue"], s["ValueType"]] for s in catalogue.settings],
        ),
    ]
    return "".join(parts)


def render() -> dict[str, str]:
    catalogue = plan()
    return {
        "source_catalogue.md": source_catalogue(catalogue),
        "data_dictionary.md": data_dictionary(catalogue),
        "mappings_and_lineage.md": mappings(catalogue),
        "quality_rules.md": quality_rules(catalogue),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate catalogue documentation.")
    parser.add_argument("--check", action="store_true", help="Fail if the committed files are stale.")
    args = parser.parse_args()

    documents = render()
    stale = []

    for name, content in documents.items():
        path = OUTPUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"Wrote {path.relative_to(ROOT)}")

    if stale:
        print(f"Stale documentation (run python scripts/generate_docs.py): {stale}")
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
