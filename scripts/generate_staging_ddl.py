"""
Write the CREATE TABLE migration for every staging table, derived from
config/source_registry.yaml (see src/warehouse/staging_schema.py).

    python scripts/generate_staging_ddl.py --output sql/016_create_staging_tables.sql

Run this when adding a source, then review and commit the migration.
A migration that has already been applied must not be edited: for a
change to an existing staging table, write a new ALTER migration. The
integration tests compare the live database with the registry, so any
mismatch is caught.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

sys.path.insert(0, str(ROOT / "src" / "validation"))
sys.path.insert(0, str(ROOT / "src" / "warehouse"))

from common import load_registry_config  # noqa: E402
from staging_schema import all_staging_tables, create_table_sql  # noqa: E402

HEADER = """USE RetailDataPlatform;
GO
SET XACT_ABORT ON;
GO
/*
    Staging tables for every registered source.
    GENERATED by scripts/generate_staging_ddl.py from
    config/source_registry.yaml - columns and types follow each source's
    validation contract; lineage columns are identical for every table.
    Existing tables (stg.Supplier) are left unchanged.
*/
"""


def render(registry_config: dict) -> str:

    parts = [HEADER]

    for definition in all_staging_tables(registry_config):
        parts.append(f"-- {definition.source}")
        parts.append(create_table_sql(definition))

    return "\n".join(parts)


def main() -> int:

    parser = argparse.ArgumentParser(description="Generate staging DDL from the registry.")
    parser.add_argument("--output", type=Path, help="File to write (default: print).")
    args = parser.parse_args()

    sql = render(load_registry_config())

    if args.output:
        args.output.write_text(sql, encoding="utf-8")
        print(f"Wrote {args.output}")
    else:
        print(sql)

    return 0


if __name__ == "__main__":
    sys.exit(main())
